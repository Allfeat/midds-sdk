//! `bench fees` — measure bond + transaction fee per `MusicalWork::deposit`.
//!
//! Records are bundled into `pallet_utility::batch_all` calls of
//! `--batch-size` deposits each (default 100, same scheme as `seed` /
//! `bench throughput`). Each inner deposit emits its own `Deposited` event
//! so per-record `bond` / `base_bond` stay accurate, but the runtime only
//! emits one `TransactionFeePaid` for the outer extrinsic — the report
//! amortises that fee across the batch's records. With batch_size=1 the
//! outer extrinsic is still a `batch_all` of one inner call, so `tx_fee`
//! is the outer-extrinsic fee and includes the small batch dispatch
//! overhead (one or two plancks at most).
//!
//! The economic model (`docs/economics.md`) splits the held bond into:
//! - `base_bond` — the unmultiplied `DepositBase + DepositPerByte × size`,
//!   refunded in full by `remove_own` within the 7-day commitment window.
//! - `premium` — the surplus generated by the dynamic multipliers
//!   (`M_fast × M_slow`), permanently transferred to the Treasury at
//!   `remove_own` or `finalize` time.
//!
//! The report exposes both halves and the corresponding total user cost,
//! plus a snapshot of the multipliers and weekly load taken at the start
//! and end of the run, so the reader can reason about the refundable vs.
//! permanent components of the deposit independently of the live
//! multiplier state.
//!
//! Submission is sequential **per signer** (Substrate enforces strictly
//! increasing nonces per account, so pipelining within a signer would race
//! the runtime). With `--signer-count` > 1, signers run concurrently up to
//! `--concurrency`, which is the realistic shape: on a live chain, deposits
//! land in concurrent blocks under non-trivial fee multiplier drift. The
//! measurement variance that this introduces is itself part of the signal.
//!
//! On batch failure the responsible worker exits (mirrors `seed` /
//! `throughput`) — a failed batch typically means broken nonce / funding
//! state, and continuing the same worker would just compound the error.
//! Surviving signers keep draining their partitions.
//!
//! Output is a markdown report grouped by payload-size buckets plus an
//! overall-percentile summary, suitable for committing to a PR or pasting
//! into a tuning discussion. Use `bench throughput` for aggregate-rate
//! measurements; the two answer distinct questions and should not be folded
//! together.

